const fs = require('fs-extra');
const path = require('path');
const packageJson = require('../package.json');

const version = process.env.VERSION || packageJson.version;
const tips = '// This file is auto generated by build/build-renderer.js';

const rendererComponents = ['MDCode', 'MDMath', 'MDMermaid'];

function buildRendererEntry(componentName) {
  const content = `${tips}
import ${componentName} from './${componentName}.vue';

// font css
import '@/assets/css/font';

const version = '${version}';

const install = (app) => {
  app.component(${componentName}.name || '${componentName.toLowerCase()}', ${componentName});
};

${componentName}.version = version;
${componentName}.install = install;

${componentName}.use = function (optionsOrInstall, opt) {
  if (typeof optionsOrInstall === 'function') {
    optionsOrInstall(${componentName}, opt);
  } else {
    optionsOrInstall.install(${componentName}, opt);
  }

  return ${componentName};
};

export default ${componentName};
`;

  fs.writeFileSync(path.join(__dirname, `../src/renderer/${componentName}.js`), content);
}

function buildRendererIndex() {
  const imports = rendererComponents.map(name => `import ${name} from './${name}.vue';`).join('\n');
  const exports = rendererComponents.map(name => `  ${name},`).join('\n');
  
  const content = `${tips}
${imports}
import { renderKatex } from './katexManager.js';

// 导出所有渲染器组件
export {
${exports}
  renderKatex
};

// 默认导出包含所有组件的对象
export default {
${exports}
  renderKatex,

  // 安装函数，用于 Vue.use()
  install(app) {
${rendererComponents.map(name => `    app.component('${name.toLowerCase()}', ${name});`).join('\n')}
  },

  version: '${version}'
};
`;

  fs.writeFileSync(path.join(__dirname, '../src/renderer/index.js'), content);
}

// 构建单个组件入口文件
rendererComponents.forEach((componentName) => {
  buildRendererEntry(componentName);
});

// 构建总入口文件
buildRendererIndex();

console.log('Renderer components build completed!');

module.exports = {
  rendererComponents,
};